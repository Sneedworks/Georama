/**
 * Every syntactic position in which one of the escape-hatch names can stand, with the verdict the portable-core
 * gate (`textRuleViolations`) must give. The sources are only ever parsed, never run.
 *
 * - `badForms`: [id, source, ...names]. The gate must report exactly one `escape hatch` violation per listed name, in
 *   order (so the count is pinned too: the same name appearing twice, as a shorthand key and value, is two entries).
 * - `goodForms`: [id, source]. The names are only names here (a member, a key, a label, a qualified right side,
 *   a variable called `constructor`), so the gate must stay silent.
 *
 * To record a new case, add one row: find the position, run the gate on it, and check the verdict against the
 * policy in `core-gate.ts` (G4) before baking it in. The suite proves the table has teeth: mutating the gate in any
 * way that changes one of these verdicts turns `core-boundary.test.ts` red.
 */
